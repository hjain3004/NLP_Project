"""Deterministic documentation generation and repository-wide checks."""

from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path
from urllib.parse import unquote

from .errors import VerificationFailure

__all__ = ["generate_phase_gates", "render_phase_gates", "verify_docs"]


_GATE_HEADER = """<!-- generated by agentctl docs generate gates; do not edit -->
# CashBooks Phase Gates

This file is generated from machine-readable criteria under `agent-system/work/`. The source
for G0 is `agent-system/work/P0/gates/G0-criteria.json`; results are written separately and
never copied into the criteria source.

## G0 — P0 control-plane gate

| Criterion | Requirement | Evidence type | Evidence source |
|---|---|---|---|
"""


def _display_evidence(criterion: dict[str, object]) -> tuple[str, str]:
    evidence_type = str(criterion["evidence_type"])
    label = evidence_type.replace("_", " ")
    if evidence_type == "deterministic_check":
        return label, "re-executed command"
    reference = criterion.get("evidence_ref")
    return label, f"`{reference}`"


def render_phase_gates(repository_root: str | Path) -> str:
    root = Path(repository_root).resolve()
    source = json.loads(
        (root / "agent-system/work/P0/gates/G0-criteria.json").read_text(encoding="utf-8")
    )
    lines = [_GATE_HEADER.rstrip("\n")]
    for criterion in source["criteria"]:
        label, evidence = _display_evidence(criterion)
        statement = str(criterion["statement"]).replace("|", "\\|")
        lines.append(
            f"| {criterion['criterion_id']} | {statement} | {label} | {evidence} |"
        )
    lines.extend(
        [
            "",
            "G0-13 and G0-14 are separate bindings derived from design criterion 13. The scope approval",
            "binds the scope-statement document set; the phase approval binds the immutable criteria file.",
            "",
            "## Later gates",
            "",
            "G1, G2, G3-B, and G3-L criteria are intentionally not transcribed during P0. Each set is",
            "materialized at its preceding gate against real repository state and accepted interfaces.",
        ]
    )
    return "\n".join(lines) + "\n"


def generate_phase_gates(repository_root: str | Path) -> Path:
    root = Path(repository_root).resolve()
    destination = root / "docs/program/PHASE_GATES.md"
    destination.write_text(render_phase_gates(root), encoding="utf-8")
    return destination


def _fail(message: str, **context: object) -> None:
    raise VerificationFailure(message, **context)


def _tracked_markdown(root: Path) -> list[Path]:
    result = subprocess.run(
        ["git", "ls-files", "*.md"], cwd=root, check=True, capture_output=True, text=True
    )
    return [root / line for line in result.stdout.splitlines() if line]


def _verify_banner_shape(root: Path) -> None:
    historical = (
        "BOOTSTRAP.md",
        "DESIGN_SPEC.md",
        "INFRA_PLAN.md",
        "TASKS.md",
        "TECH_SPEC.md",
        "docs/cashguard_prd_v0.2.md",
    )
    added = subprocess.run(
        ["git", "log", "--diff-filter=A", "--format=%H", "--", "docs/DOCUMENT_AUTHORITY.md"],
        cwd=root,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.splitlines()
    if not added:
        _fail("cannot locate the authority-document commit")
    parent = f"{added[-1]}^"
    for relative in historical:
        current = (root / relative).read_text(encoding="utf-8")
        if not current.startswith("> **Authority: "):
            _fail("historical document lacks its authority banner", path=relative)
        original = subprocess.run(
            ["git", "show", f"{parent}:{relative}"],
            cwd=root,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
        lines = current.splitlines(keepends=True)
        if len(lines) < 4 or lines[3].strip() or "".join(lines[4:]) != original:
            _fail("authority banner is not an exact four-line insertion", path=relative)


def _verify_links(root: Path, paths: list[Path]) -> None:
    pattern = re.compile(r"(?<!!)\[[^\]]+\]\(([^)]+)\)")
    for path in paths:
        text = path.read_text(encoding="utf-8")
        for raw in pattern.findall(text):
            target = raw.strip().split()[0].strip("<>")
            if target.startswith(("http://", "https://", "mailto:", "#")):
                continue
            target = unquote(target.split("#", 1)[0].split("?", 1)[0])
            if not target:
                continue
            candidate = (path.parent / target).resolve()
            try:
                candidate.relative_to(root)
            except ValueError:
                _fail("Markdown link escapes the repository", path=str(path), target=raw)
            if not candidate.exists():
                root_relative = (root / target).resolve()
                try:
                    root_relative.relative_to(root)
                except ValueError:
                    pass
                else:
                    if root_relative.exists():
                        continue
                _fail("Markdown link target does not exist", path=str(path), target=raw)


def _verify_claims(root: Path, paths: list[Path]) -> None:
    forbidden = (
        "finished" + " app",
        "production" + "-ready",
        "supports Foundation" + " Models",
        "ships with Foundation" + " Models",
        "App" + " Store",
    )
    mandated_negative = "G3 is not a " + forbidden[0] + " and must never be described as one."
    active_scope_negative = "Not that a " + forbidden[0] + " exists."
    for path in paths:
        relative = path.relative_to(root).as_posix()
        if relative.startswith(("docs/archive/", "docs/superpowers/")) or relative == "docs/program/ROADMAP.md":
            continue
        text = path.read_text(encoding="utf-8")
        if text.startswith("> **Authority: "):
            continue
        scrubbed = text.replace(mandated_negative, "").replace(active_scope_negative, "")
        if relative == "docs/product/NON_GOALS.md":
            continue
        for phrase in forbidden:
            if phrase.lower() in scrubbed.lower():
                _fail("active documentation contains a forbidden product claim", path=relative, phrase=phrase)


def verify_docs(repository_root: str | Path) -> dict[str, object]:
    root = Path(repository_root).resolve()
    _verify_banner_shape(root)

    agents = (root / "AGENTS.md").read_text(encoding="utf-8")
    headings = re.findall(r"^## (\d+)\. ", agents, re.MULTILINE)
    if headings != [str(index) for index in range(1, 12)]:
        _fail("AGENTS.md does not have the exact ordered eleven sections", headings=headings)
    for sentence in (
        "G3 is not a finished app and must never be described as one.",
        "Live Foundation Models support is not claimed before G3-L.",
    ):
        if sentence not in agents:
            _fail("AGENTS.md lacks a claims-discipline sentence", sentence=sentence)
    if re.search(r"\b(claude|codex|anthropic|openai|gpt-5(?:\.[0-9]+)?)\b", agents, re.I):
        _fail("AGENTS.md is not provider-neutral")

    first = "Before doing anything else, read `AGENTS.md` in full. It is the canonical engineering constitution."
    for relative, ceiling in (("CLAUDE.md", 60), ("GEMINI.md", 40)):
        lines = (root / relative).read_text(encoding="utf-8").splitlines()
        if not lines or lines[0] != first or len(lines) > ceiling:
            _fail("vendor adapter shape is invalid", path=relative, lines=len(lines))

    required = (
        "docs/DOCUMENT_AUTHORITY.md",
        "docs/archive/README.md",
        "docs/product/ACTIVE_SCOPE.md",
        "docs/product/HERO_SCENARIO.md",
        "docs/product/NON_GOALS.md",
        "docs/security/INVARIANTS.md",
        "docs/security/PRIVACY_BOUNDARY.md",
        "docs/architecture/CONCURRENCY.md",
        "docs/decisions/README.md",
        "docs/program/ROADMAP.md",
        "docs/program/PROGRAM_DAG.md",
        "docs/program/PHASE_GATES.md",
    )
    missing = [relative for relative in required if not (root / relative).is_file()]
    if missing:
        _fail("required documentation is absent", missing=missing)

    adr_headings = (
        "ID and title",
        "Status",
        "Context",
        "Considered options",
        "Decision",
        "Consequences",
        "Affected contracts and locks",
        "Supersedes",
        "Required approvals",
        "References",
    )
    adrs = sorted((root / "docs/decisions").glob("ADR-*.md"))
    if len(adrs) != 5:
        _fail("the decision record must contain exactly five ADRs", count=len(adrs))
    for path in adrs:
        text = path.read_text(encoding="utf-8")
        if not re.search(r"^status:\s*accepted\s*$", text, re.I | re.M):
            _fail("ADR is not accepted", path=path.name)
        actual = re.findall(r"^## (.+)$", text, re.MULTILINE)
        if actual != list(adr_headings):
            _fail("ADR headings differ from the ten-heading contract", path=path.name)

    role_headings = ["Owns", "May not", "Required output artifacts", "Escalation triggers", "Independence rules"]
    roles = sorted((root / "agent-system/roles").glob("*.md"))
    if len(roles) != 7:
        _fail("there must be exactly seven role contracts", count=len(roles))
    for path in roles:
        if re.findall(r"^## (.+)$", path.read_text(encoding="utf-8"), re.MULTILINE) != role_headings:
            _fail("role headings differ from the five-heading contract", path=path.name)

    authority = (root / "docs/DOCUMENT_AUTHORITY.md").read_text(encoding="utf-8")
    block = authority.split("## Authority order", 1)[1].split("```text\n", 1)[1].split("\n```", 1)[0] + "\n"
    policy = json.loads((root / "agent-system/policies/document-authority.json").read_text())
    if block != policy["authority_block"]:
        _fail("document authority prose and policy differ")
    if (root / "docs/program/PHASE_GATES.md").read_text() != render_phase_gates(root):
        _fail("generated phase-gate documentation is stale")

    non_goals = (root / "docs/product/NON_GOALS.md").read_text(encoding="utf-8")
    named_non_goals = (
        "SwiftUI screens and navigation", "design tokens", "animation",
        "UI accessibility presentation", "UI automation", "Plaid",
        "backend or network sync", "Share Extension",
        "standalone image or camera ingestion", "broader accounting workflows",
        "App Store or TestFlight operations",
        "any recruiter-facing claim of a finished product",
    )
    for item in named_non_goals:
        if item not in non_goals:
            _fail("NON_GOALS.md is missing a required literal", item=item)

    identifier_pattern = r"\b((?:FIN|AI|PRIV|PLAT)-\d{2})\b"
    agent_ids = set(re.findall(identifier_pattern, agents))
    doc_ids = set(re.findall(identifier_pattern, (root / "docs/security/INVARIANTS.md").read_text()))
    policy_ids = {entry["id"] for entry in json.loads((root / "agent-system/policies/invariants.json").read_text())["entries"]}
    if not (agent_ids == doc_ids == policy_ids) or len(policy_ids) != 26:
        _fail("the three invariant catalogs do not contain the same twenty-six IDs")

    markdown = _tracked_markdown(root)
    _verify_links(root, markdown)
    _verify_claims(root, markdown)
    return {"status": "ok", "markdown_files_checked": len(markdown)}
